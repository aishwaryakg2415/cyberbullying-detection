"""Generate all figures + tables from saved results, and the caption files.

Usage:  python scripts/analyze_results.py && python scripts/generate_paper_assets.py
Figures -> results/figures/<group>/ (PNG 300 dpi + PDF + CSV/JSON data)
Tables  -> results/tables/ (CSV + LaTeX + Markdown)
Captions -> paper/FIGURE_CAPTIONS.md, paper/TABLE_CAPTIONS.md
Any figure whose inputs do not exist yet is listed as PENDING (never drawn empty).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.evaluation.aggregate import collect_runs  # noqa: E402
from src.reporting import figures as F  # noqa: E402
from src.reporting import tables as T  # noqa: E402
from src.reporting.diagrams import all_diagrams  # noqa: E402
from src.utils.io import FIG_DIR, PAPER_DIR, RESULTS_DIR, TABLE_DIR, load_json  # noqa: E402


def main() -> int:
    an_path = RESULTS_DIR / "analysis" / "analysis.json"
    an = load_json(an_path) if an_path.exists() else {}
    groups = collect_runs()
    figs, tabs, pending = [], [], []
    all_diagrams(FIG_DIR / "diagrams", figs, PAPER_DIR / "diagrams")
    jobs = [
        ("data", lambda o: F.dataset_distributions(o, figs)),
        ("data", lambda o: F.language_distribution(o, figs, an)),
        ("training", lambda o: F.training_curves(o, figs, an)),
        ("evaluation", lambda o: F.confusion(o, figs, groups)),
        ("evaluation", lambda o: F.roc_pr(o, figs, groups)),
        ("comparison", lambda o: F.model_comparison(o, figs, an)),
        ("ablation", lambda o: F.ablation(o, figs, an)),
        ("explainability", lambda o: F.shap_heatmaps(o, figs)),
        ("explainability", lambda o: F.faithfulness_fig(o, figs)),
        ("error_analysis", lambda o: F.error_slices(o, figs, an)),
        ("runtime", lambda o: F.runtime_size(o, figs)),
        ("calibration", lambda o: F.calibration_fig(o, figs, groups)),
        ("early_detection", lambda o: F.early_curves(o, figs)),
    ]
    for sub, fn in jobs:
        try:
            ok = fn(FIG_DIR / sub) if an or sub == "data" else False
        except KeyError as e:
            ok = False
            print(f"[pending] {sub}: missing {e}")
        if not ok:
            pending.append(f"{sub}: {fn.__code__.co_names[-1] if fn.__code__.co_names else sub}")
    T.dataset_tables(TABLE_DIR, tabs)
    T.config_table(TABLE_DIR, tabs)
    if an:
        T.results_tables(TABLE_DIR, tabs, an)
        T.shift_tables(TABLE_DIR, tabs, an)
    T.runtime_table(TABLE_DIR, tabs)
    T.early_table(TABLE_DIR, tabs)
    T.explain_table(TABLE_DIR, tabs)

    def caption_md(items, title):
        lines = [f"# {title}", "", "*Auto-generated by `scripts/generate_paper_assets.py` from saved results. "
                 "Every asset has its underlying data next to it (CSV/JSON).*", ""]
        for it in items:
            rel = Path(it["file"]).relative_to(Path.cwd()) if Path(it["file"]).is_absolute() else Path(it["file"])
            lines.append(f"- **`{rel}`** — {it['caption']}")
        if pending and "Figure" in title:
            lines += ["", "## Pending (inputs not yet available — not drawn)", ""] + [f"- {p}" for p in pending]
        return "\n".join(lines) + "\n"

    root = Path(__file__).resolve().parents[1]
    for it in figs + tabs:
        it["file"] = str(Path(it["file"]).resolve().relative_to(root))
    (PAPER_DIR / "FIGURE_CAPTIONS.md").write_text(caption_md(figs, "Figure captions"), encoding="utf-8")
    (PAPER_DIR / "TABLE_CAPTIONS.md").write_text(caption_md(tabs, "Table captions"), encoding="utf-8")
    print(f"figures: {len(figs)}  tables: {len(tabs)}  pending: {pending}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
